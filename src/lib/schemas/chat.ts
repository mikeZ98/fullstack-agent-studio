import { z } from "zod";

import { LIMITS } from "./limits";
import { IdentifierSchema } from "./primitives";
import { MessageMetadataSchema } from "./ui-message";

/**
 * Contracts of the chat API: what the AI SDK's `DefaultChatTransport` POSTs to
 * /api/chat, and the reduced body forwarded to the agent backend.
 */

/** Only text is forwarded upstream; its shape is validated. */
export const ChatTextPartSchema = z.object({
  type: z.literal("text"),
  text: z.string().max(LIMITS.messageTextChars),
  state: z.enum(["streaming", "done"]).optional(),
});
export type ChatTextPart = z.infer<typeof ChatTextPartSchema>;

/**
 * Any other UI part (tool calls, data-artifact-*, step markers, ...) the client echoes
 * back in history. Accepted but reduced to its type: the server never reads its content.
 */
export const ChatOtherPartSchema = z.object({
  type: z
    .string()
    .min(1)
    .max(64)
    .regex(/^[a-z][a-z0-9-]*$/, "Must be a part type")
    .refine((type) => type !== "text", "Text parts must be valid text parts"),
});
export type ChatOtherPart = z.infer<typeof ChatOtherPartSchema>;

export const ChatMessageSchema = z.strictObject({
  id: IdentifierSchema,
  /** `system` is rejected: clients must never inject system prompts. */
  role: z.enum(["user", "assistant"]),
  metadata: MessageMetadataSchema.optional(),
  parts: z.array(z.union([ChatTextPartSchema, ChatOtherPartSchema])).max(LIMITS.messageParts),
});
export type ChatMessage = z.infer<typeof ChatMessageSchema>;

/** Text carried by a message's text parts, joined the way the agent receives it. */
export function messageText(message: Pick<ChatMessage, "parts">): string {
  return message.parts
    .flatMap((part) => ("text" in part ? [part.text] : []))
    .join("\n\n")
    .trim();
}

export const ChatRequestSchema = z
  .strictObject({
    /** Chat (conversation) id generated by the client. */
    id: IdentifierSchema,
    messages: z.array(ChatMessageSchema).min(1).max(LIMITS.chatMessages),
    trigger: z.enum(["submit-message", "regenerate-message"]),
    messageId: IdentifierSchema.optional(),
  })
  .superRefine((request, ctx) => {
    const lastIndex = request.messages.length - 1;
    const last = request.messages[lastIndex];
    if (last?.role !== "user") {
      ctx.addIssue({
        code: "custom",
        path: ["messages", lastIndex, "role"],
        message: "The last message must come from the user",
      });
    } else if (messageText(last) === "") {
      ctx.addIssue({
        code: "custom",
        path: ["messages", lastIndex, "parts"],
        message: "The last message must contain text",
      });
    }
    let total = 0;
    for (const message of request.messages) {
      for (const part of message.parts) if ("text" in part) total += part.text.length;
    }
    if (total > LIMITS.chatHistoryChars) {
      ctx.addIssue({
        code: "custom",
        path: ["messages"],
        message: `Conversation exceeds ${LIMITS.chatHistoryChars} characters of text`,
      });
    }
  });
export type ChatRequest = z.infer<typeof ChatRequestSchema>;

export const AgentMessageSchema = z.strictObject({
  role: z.enum(["user", "assistant"]),
  content: z.string().min(1),
});
export type AgentMessage = z.infer<typeof AgentMessageSchema>;

/** Body POSTed to BACKEND_SSE_URL. */
export const AgentRequestSchema = z.strictObject({
  chatId: IdentifierSchema,
  messages: z.array(AgentMessageSchema).min(1).max(LIMITS.chatMessages),
});
export type AgentRequest = z.infer<typeof AgentRequestSchema>;

/** Reduce a UI chat request to the agent protocol: text only, empty turns dropped. */
export function toAgentRequest(request: ChatRequest): AgentRequest {
  const messages = request.messages.flatMap((message) => {
    const content = messageText(message);
    return content === "" ? [] : [{ role: message.role, content }];
  });
  return { chatId: request.id, messages };
}
